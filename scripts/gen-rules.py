"""Generates lib/rules-data.ts (the website's Rules tab) from the moderation bot's db/rules_content.py.

    python3 scripts/gen-rules.py /path/to/Moderation/db/rules_content.py

Discord-only bits are adapted: channel and role tokens become plain names, and any point that shows the join
password is left out (the password is only in Discord's #rules).
"""

import importlib.util
import json
import re
import sys
from pathlib import Path

src = Path(sys.argv[1])
spec = importlib.util.spec_from_file_location("rules_content", src)
RC = importlib.util.module_from_spec(spec)
spec.loader.exec_module(RC)


def web(text: str) -> str:
    text = re.sub(r"\[\[ch:(\w+)\]\]", lambda m: RC.CHANNELS[m.group(1)][1], text)
    return re.sub(r"\[\[role:(\w+)\]\]", lambda m: RC.ROLES[m.group(1)][1], text)


parts = []
for part in RC.numbered_parts():
    parts.append({
        "key": part["key"],
        "title": part["title"].split(" · ", 1)[-1],
        "label": part["title"].split(" · ", 1)[0],
        "emoji": part["emoji"],
        "color": "#%02x%02x%02x" % tuple(part["color"]),
        "intro": web(part.get("intro", "")),
        "rules": [
            {
                "n": r["n"],
                "title": r["title"],
                "points": [web(p) for p in r["points"] if "{PASSWORD}" not in p],
                "bad": [web(x) for x in r.get("examples", {}).get("bad", [])],
                "good": [web(x) for x in r.get("examples", {}).get("good", [])],
            }
            for r in part["rules"]
        ],
        "info": [{"title": t, "body": web(b)} for t, b in part.get("info", [])],
    })

data = {"intro": web(RC.INTRO), "tldr": [web(t) for t in RC.TLDR], "parts": parts}
out = Path(__file__).resolve().parent.parent / "lib" / "rules-data.ts"
out.write_text(
    "// GENERATED by scripts/gen-rules.py from the moderation bot's db/rules_content.py. Don't edit by hand:\n"
    "// change the bot file, run the script, and run /rules refresh in Discord so both stay the same.\n"
    "// Text uses **bold** and [links](url).\n\n"
    "export type Rule = { n: number; title: string; points: string[]; bad: string[]; good: string[] };\n"
    "export type RulePart = { key: string; title: string; label: string; emoji: string; color: string; intro: string; rules: Rule[]; info: { title: string; body: string }[] };\n\n"
    f"export const RULES: {{ intro: string; tldr: string[]; parts: RulePart[] }} = {json.dumps(data, ensure_ascii=False, indent=2)};\n"
)
print(f"Wrote {out} ({sum(len(p['rules']) for p in parts)} rules)")

# The raw text (with Discord tokens), the starting point for Admin → Rules and what the bot falls back to
source = {
    "intro": RC.INTRO,
    "tldr": list(RC.TLDR),
    "parts": [
        {
            "key": p["key"],
            "title": p["title"],
            "emoji": p["emoji"],
            "color": list(p["color"]),
            "intro": p.get("intro", ""),
            "rules": [{"title": r["title"], "points": list(r["points"]), "bad": list(r.get("examples", {}).get("bad", [])), "good": list(r.get("examples", {}).get("good", []))} for r in p["rules"]],
            "info": [list(i) for i in p.get("info", [])],
        }
        for p in RC.PARTS
    ],
}
names = {"channels": {k: v[1] for k, v in RC.CHANNELS.items()}, "roles": {k: v[1] for k, v in RC.ROLES.items()}}
out2 = Path(__file__).resolve().parent.parent / "lib" / "rules-source.ts"
out2.write_text(
    "// GENERATED by scripts/gen-rules.py from the moderation bot's db/rules_content.py: the rules as written there, with\n"
    "// Discord tokens ([[ch:key]], [[role:key]], {PASSWORD}). Admin → Rules starts from this; edits are saved in zeo_bot.rules_content.\n\n"
    "export type RuleSource = { title: string; points: string[]; bad: string[]; good: string[] };\n"
    "export type RulePartSource = { key: string; title: string; emoji: string; color: number[]; intro: string; rules: RuleSource[]; info: string[][] };\n"
    "export type RulesSource = { intro: string; tldr: string[]; parts: RulePartSource[] };\n\n"
    f"export const RULES_SOURCE: RulesSource = {json.dumps(source, ensure_ascii=False, indent=2)};\n\n"
    f"/** How channel and role tokens read on the website */\nexport const RULE_NAMES: {{ channels: Record<string, string>; roles: Record<string, string> }} = {json.dumps(names, ensure_ascii=False, indent=2)};\n"
)
print(f"Wrote {out2}")
